import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const base=path.dirname(fileURLToPath(import.meta.url));
const read=name=>fs.readFileSync(path.join(base,name),'utf8');
let document=read('document-shell.html');
let requirements=read('requirements-sections.html');
const sections=[...requirements.matchAll(/<section\b[\s\S]*?<\/section>/g)].map(m=>m[0]);
if(sections.length!==13)throw new Error('Unexpected requirements section count: '+sections.length);
const purpose=sections.find(s=>s.includes('id="req-purpose"'));
const layout=sections.find(s=>s.includes('id="req-layout"'));
document=document.replace('<!-- PURPOSE_CONTENT -->',()=>purpose+'\n'+layout);
document=document.replace('<!-- WORKSPACE_CONTENT -->',()=>read('workspace-demo.html'));
const combined=read('entry-and-state.html');
const split=combined.indexOf('<section class="doc-section" id="state-demo">');
if(split<0)throw new Error('State section boundary missing');
document=document.replace('<!-- ENTRY_CONTENT -->',()=>combined.slice(0,split));
document=document.replace('<!-- STATE_CONTENT -->',()=>combined.slice(split));
document=document.replace('<!-- SCENARIO_CONTENT -->',()=>read('scenario-demo.html').replace('<section id="scenario-demo"','<section class="doc-section" id="scenario-demo"'));
document=document.replace('<!-- CHART_CONTENT -->',()=>read('chart-demo.html').replace('<section id="chart-demo"','<section class="doc-section" id="chart-demo"'));
document=document.replace('<!-- REQUIREMENTS_CONTENT -->',()=>sections.filter(s=>s!==purpose&&s!==layout).join('\n')+'\n'+read('handoff-contracts.html'));
document=document.replaceAll('req-comparison','req-analytics').replaceAll('req-state','req-persistence').replaceAll('req-priorities','req-priority');
document=document.replace('__REFERENCE_MAIN__','data:image/png;base64,'+fs.readFileSync(path.join(base,'Screenshot 2026-11-01 at 07.47.50.png')).toString('base64'));
document=document.replace('__REFERENCE_FACTOR__','data:image/png;base64,'+fs.readFileSync(path.join(base,'vennbytwosigma-20250513120141.png')).toString('base64'));
if(/<!-- [A-Z_]+_CONTENT -->|__REFERENCE_/.test(document))throw new Error('Unresolved build marker');
const destination=path.join(base,'portfolio-analytics-requirements.html');
fs.writeFileSync(destination,document);
console.log(destination+'\n'+Buffer.byteLength(document)+' bytes; '+(document.match(/<section\b/g)||[]).length+' sections');
